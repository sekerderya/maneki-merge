/**
 * The Frog's art (docs/ART_ASSETS.md §4.22, GAME_DESIGN §15.17): the frog's four poses from
 * `art-source/specials/frog` and its tongue from `art-source/fx/frog-tongue`, written to
 * `public/assets/specials/frog-*.webp` and `public/assets/fx/frog-tongue*.webp` with their
 * measurements in `src/config/frogSpriteData.ts`. A missing image leaves its part `null`, and the
 * game draws a stand-in.
 *
 * - The frog sheet is a 2×2 grid of one frog: calm, mouth open, gulping and sleepy. Each quarter goes
 *   through tools/artBall.ts like a cat (its eyes stand above the body circle like a cat's ears).
 * - The tongue sheet holds a straight band across the top half and the tongue's round tip below it.
 *   The band's ends came drawn round, so only a slice from its even middle is kept: the game
 *   stretches it from the frog's mouth to the cat. The tip is cropped to itself; its flat left side
 *   joins the band.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { buildBall } from './artBall.ts';
import type { BallSprite } from './artBall.ts';
import {
  components,
  crop,
  cutBackground,
  findSource,
  isolate,
  loadRgba,
  round,
  saveWebp,
} from './artImage.ts';
import type { Rgba } from './artImage.ts';

const SPECIAL_DIR = 'art-source/specials';
const FX_DIR = 'art-source/fx';
const SPECIAL_OUT = 'public/assets/specials';
const FX_OUT = 'public/assets/fx';
const DATA_FILE = 'src/config/frogSpriteData.ts';
/** The poses in the sheet's reading order. */
const POSES = ['calm', 'open', 'gulp', 'sleepy'] as const;
/** The share of the band's length kept, from its middle (its ends are drawn round). */
const BAND_SLICE = { from: 0.22, to: 0.42 } as const;

interface TongueSpriteData {
  readonly file: string;
  readonly width: number;
  readonly height: number;
}

interface FrogData {
  /** Calm, mouth open, gulping, sleepy. */
  readonly poses: BallSprite[] | null;
  /** A slice of the tongue's band, stretched along its length. */
  readonly band: TongueSpriteData | null;
  /** The tongue's round tip; its left edge joins the band. */
  readonly tip: TongueSpriteData | null;
}

export async function buildFrog(): Promise<void> {
  const find = (dir: string, base: string): Promise<string | null> =>
    findSource(dir, base).catch(() => null);
  const [frog, tongue] = await Promise.all([
    find(SPECIAL_DIR, 'frog'),
    find(FX_DIR, 'frog-tongue'),
  ]);
  await mkdir(SPECIAL_OUT, { recursive: true });
  await mkdir(FX_OUT, { recursive: true });

  let poses: BallSprite[] | null = null;
  if (frog) {
    const sheet = await loadRgba(frog);
    const w = Math.floor(sheet.width / 2);
    const h = Math.floor(sheet.height / 2);
    poses = [];
    for (const [i, pose] of POSES.entries()) {
      const quarter = crop(sheet, { x: (i % 2) * w, y: Math.floor(i / 2) * h, w, h });
      poses.push(await buildBall(quarter, SPECIAL_OUT, `frog-${pose}.webp`));
    }
  }

  let band: TongueSpriteData | null = null;
  let tip: TongueSpriteData | null = null;
  if (tongue) {
    const image = await loadRgba(tongue);
    cutBackground(image);
    const [first, second] = components(image);
    if (!first || !second) throw new Error(`${tongue}: expected the band and the tip`);
    // The band is the piece higher up.
    const [bandPiece, tipPiece] = first.y < second.y ? [first, second] : [second, first];
    const whole = isolate(image, bandPiece, 0);
    const from = Math.round(whole.width * BAND_SLICE.from);
    const to = Math.round(whole.width * BAND_SLICE.to);
    band = await save(
      crop(whole, { x: from, y: 0, w: to - from, h: whole.height }),
      'frog-tongue.webp',
    );
    tip = await save(isolate(image, tipPiece, 0), 'frog-tongue-tip.webp');
  }

  await writeFile(DATA_FILE, dataModule({ poses, band, tip }));
  console.log(
    `Frog: ${poses ? `${poses.length} poses` : 'no frog'}, ` +
      `${band && tip ? `tongue ${band.height}px thick, tip ${tip.width}×${tip.height}` : 'no tongue'}; ` +
      `wrote ${DATA_FILE}`,
  );
}

async function save(image: Rgba, file: string): Promise<TongueSpriteData> {
  await saveWebp(image, join(FX_OUT, file));
  return { file, width: image.width, height: round(image.height) };
}

function dataModule(data: FrogData): string {
  return `/**
 * Generated by tools/build-art.ts (\`npm run art\`) from art-source/specials/frog and
 * art-source/fx/frog-tongue: do not edit by hand. See frogSprites.ts for each field.
 */
import type { FrogSprites } from './frogSprites';

export const FROG_SPRITE_DATA: FrogSprites = ${JSON.stringify(data, null, 2)};
`;
}
